CREATE TABLE IF NOT EXISTS batches (
  signature TEXT PRIMARY KEY,
  wallet TEXT NOT NULL,
  tile INTEGER NOT NULL,
  commit TEXT NOT NULL,
  credits INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS batch_bytes (
  signature TEXT PRIMARY KEY REFERENCES batches(signature) ON DELETE CASCADE,
  batch_bytes BYTEA NOT NULL
);

CREATE TABLE IF NOT EXISTS placements (
  id SERIAL PRIMARY KEY,
  signature TEXT NOT NULL REFERENCES batches(signature) ON DELETE CASCADE,
  tile INTEGER NOT NULL,
  x INTEGER NOT NULL,
  y INTEGER NOT NULL,
  color INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
